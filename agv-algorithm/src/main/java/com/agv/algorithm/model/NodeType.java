package com.agv.algorithm.model;

/**
 * 路网节点类型。
 * <p>
 * 节点类型只表达会改变算法或校验分支的行为：能否作为任务端点、装货还是卸货、
 * 是否回充、是否空闲停放、是否只能停靠等待、是否按临界区处理。
 * 车间里的区域（充电区、存储区等）不是节点类型，见 {@link ZoneKind}。
 */
public enum NodeType {
    /** 拣货位：装货任务起点，装货发生地 */
    PICKING,
    /** 上货位：卸货任务终点，卸货发生地 */
    LOADING,
    /** 存储位：货架取放口，可作装货或卸货端点 */
    STORAGE,
    /** 充电位：AGV 初始停放位与回充点 */
    CHARGER,
    /** 停放位：任务完成后的空闲停放点 */
    PARKING,
    /** 缓存位：等待避障时的安全停靠点 */
    BUFFER,
    /** 路口 */
    JUNCTION
}
